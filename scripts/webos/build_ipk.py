#!/usr/bin/env python3
"""Build and verify webOS ARM, then atomically replace <Aurora root>/aurora.ipk."""

import argparse
import datetime
import hashlib
import io
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tarfile
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "dev"))
from aurora_version import check_contract
from comparison_snapshot import repository

APP_ID = "com.aurora.gamestream"

# Runs in Linux/amd64, never on the TV; source is mounted read-only.
DOCKER_BUILD = r'''
set -euo pipefail
if ! command -v ares-package >/dev/null; then
    curl --fail --location --retry 3 -o /tmp/ares-package.deb \
      https://github.com/webosbrew/ares-cli-rs/releases/download/20241111-d97ba96/ares-package_0.1.4-1_amd64.deb
    dpkg -i /tmp/ares-package.deb
fi
sdk=/tmp/arm-webos-linux-gnueabi_sdk-buildroot
if [ ! -f "$sdk/share/buildroot/toolchainfile.cmake" ]; then
    archive=/tmp/arm-webos-linux-gnueabi_sdk-buildroot-x86_64.tar.gz
    if [ ! -f "$archive" ]; then
        curl --fail --location --retry 3 -o "$archive.partial" \
          https://github.com/openlgtv/buildroot-nc4/releases/download/webos-a38c582/arm-webos-linux-gnueabi_sdk-buildroot-x86_64.tar.gz
        mv "$archive.partial" "$archive"
    fi
    tar -xzf "$archive" -C /tmp
    "$sdk/relocate-sdk.sh"
fi
export CI=1
cmake -S /build -B /tmp/aurora-webos-build \
    -DCMAKE_TOOLCHAIN_FILE="$sdk/share/buildroot/toolchainfile.cmake" \
    -DCMAKE_C_COMPILER="$sdk/bin/arm-webos-linux-gnueabi-gcc" \
    -DCMAKE_CXX_COMPILER="$sdk/bin/arm-webos-linux-gnueabi-g++" \
    -DCMAKE_BUILD_TYPE="$1" -DTARGET_WEBOS=ON -DBUILD_TESTS=OFF -DBUILD_UI_SIM=OFF \
    -DCMAKE_TRY_COMPILE_TARGET_TYPE=STATIC_LIBRARY -DTHREADS_PTHREAD_ARG=2
cmake --build /tmp/aurora-webos-build --parallel "$2"
cd /tmp/aurora-webos-build
cpack --config CPackConfig.cmake -B /artifacts
'''


def ar_members(path):
    result = {}
    with path.open("rb") as source:
        if source.read(8) != b"!<arch>\n":
            raise ValueError("Expected a Debian/ar IPK generated by ares-package")
        while True:
            header = source.read(60)
            if not header:
                break
            if len(header) != 60 or header[58:] != b"`\n":
                raise ValueError("Invalid IPK ar header")
            size = int(header[48:58])
            name = header[:16].decode("ascii").strip().rstrip("/")
            if size < 0 or size > path.stat().st_size or name in result:
                raise ValueError("Invalid IPK member")
            payload = source.read(size)
            if len(payload) != size:
                raise ValueError("Truncated IPK member")
            result[name] = payload
            if size % 2 and len(source.read(1)) != 1:
                raise ValueError("Missing ar padding")
    if result.get("debian-binary") != b"2.0\n":
        raise ValueError("Invalid Debian package version marker")
    return result


def tar_entry(archive, name):
    matches = [member for member in archive.getmembers()
               if member.name.removeprefix("./") == name and member.isfile()]
    if len(matches) != 1:
        raise ValueError(f"Expected one package entry: {name}")
    return archive.extractfile(matches[0]).read()


def verify_ipk(path, version):
    members = ar_members(path)
    data_names = [name for name in members if name.startswith("data.tar.")]
    control_names = [name for name in members if name.startswith("control.tar.")]
    if len(data_names) != 1 or len(control_names) != 1:
        raise ValueError("IPK must contain one data archive and one control archive")
    with tarfile.open(fileobj=io.BytesIO(members[control_names[0]]), mode="r:*") as archive:
        control = tar_entry(archive, "control").decode()
    fields = dict(line.split(": ", 1) for line in control.splitlines() if ": " in line)
    for key, expected in (("Package", APP_ID), ("Version", version), ("Architecture", "arm")):
        if fields.get(key) != expected:
            raise ValueError(f"Control {key}: expected {expected!r}, got {fields.get(key)!r}")
    with tarfile.open(fileobj=io.BytesIO(members[data_names[0]]), mode="r:*") as archive:
        base = f"usr/palm/applications/{APP_ID}/"
        app = json.loads(tar_entry(archive, base + "appinfo.json"))
        if (app.get("id"), app.get("version"), app.get("main")) != (APP_ID, version, "bin/aurora"):
            raise ValueError("appinfo identity, version or entrypoint does not match the build")
        if tar_entry(archive, base + "aurora-logs-reset.pending") != b"aurora-log-reset-v1\n":
            raise ValueError("Package is missing the valid installation log-reset marker")
        binary = tar_entry(archive, base + "bin/aurora")
        if binary[:6] != b"\x7fELF\x01\x01" or len(binary) < 52 or int.from_bytes(binary[18:20], "little") != 40:
            raise ValueError("Package entrypoint is not a 32-bit little-endian ARM ELF")
        if f"aurora-v{version}".encode() + b"\0" not in binary:
            raise ValueError("ELF build tag differs from the central version")
    return {"id": APP_ID, "version": version, "architecture": "arm", "arm_elf_verified": True,
            "installation_log_reset_verified": True,
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "size_bytes": path.stat().st_size}


def publish(package, root, version):
    # Verify before touching the previously delivered installer.
    metadata = verify_ipk(package, version)
    target = root / "aurora.ipk"
    with tempfile.NamedTemporaryFile(dir=root, prefix=".aurora-ipk-", delete=False) as staged:
        temporary = Path(staged.name)
        try:
            with package.open("rb") as source:
                shutil.copyfileobj(source, staged)
            staged.flush()
            os.fsync(staged.fileno())
            staged.close()
            temporary.chmod(0o644)
            os.replace(temporary, target)
        finally:
            temporary.unlink(missing_ok=True)
    return target, metadata


def run(command, log, cwd, env=None):
    log.write("\nCOMMAND " + json.dumps(command) + "\n")
    log.flush()
    subprocess.run(command, cwd=cwd, env=env, stdout=log, stderr=subprocess.STDOUT, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--backend", choices=("auto", "docker", "native"), default="auto")
    parser.add_argument("--build-type", choices=("Release", "RelWithDebInfo", "Debug"), default="RelWithDebInfo")
    parser.add_argument("--jobs", type=int, default=min(os.cpu_count() or 2, 6))
    parser.add_argument("--image", default="aurora-webos-builder:local")
    parser.add_argument("--volume", default="aurora-webos-build-cache")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    root = args.root.resolve()
    run_dir = None
    try:
        version = check_contract(root)
        modules = subprocess.check_output(["git", "-C", str(root), "submodule", "status", "--recursive"], text=True)
        if any(line.startswith(("-", "U")) for line in modules.splitlines()):
            raise ValueError("Initialize/resolve required submodules before building; no checkout is changed automatically")
        backend = args.backend
        if backend == "auto":
            backend = "native" if platform.system() == "Linux" and os.environ.get("TOOLCHAIN_FILE") else "docker"
        print(f"Aurora {version}; backend={backend}; output={root / 'aurora.ipk'}", flush=True)
        if args.dry_run:
            print("Dry run: no build, download, version change or package replacement.")
            return 0
        if backend == "native" and not Path(os.environ.get("TOOLCHAIN_FILE", "/missing-toolchain")).is_file():
            raise ValueError("Native build requires TOOLCHAIN_FILE pointing to the webOS SDK")
        run_dir = Path(tempfile.mkdtemp(prefix="run-", dir=make_cache(root)))
        artifacts = run_dir / "packages"
        artifacts.mkdir()
        state = repository(root)
        (run_dir / "source.json").write_text(json.dumps(state, indent=2) + "\n")
        print(f"Build log: {run_dir / 'build.log'}", flush=True)
        with (run_dir / "build.log").open("w") as log:
            if backend == "docker":
                if not shutil.which("docker"):
                    raise ValueError("Docker is required on this host; start Docker Desktop or configure a native Linux SDK")
                exists = subprocess.run(["docker", "image", "inspect", args.image], stdout=subprocess.DEVNULL,
                                        stderr=subprocess.DEVNULL).returncode == 0
                if not exists:
                    run(["docker", "build", "--platform", "linux/amd64", "-t", args.image,
                         "-f", "scripts/webos/Dockerfile.build", "."], log, root)
                run(["docker", "run", "--rm", "--platform", "linux/amd64", "--entrypoint", "bash",
                     "--volume", f"{root}:/build:ro", "--volume", f"{args.volume}:/tmp",
                     "--volume", f"{artifacts}:/artifacts", args.image, "-c", DOCKER_BUILD,
                     "aurora-build", args.build_type, str(args.jobs)], log, root)
            else:
                env = dict(os.environ, CI="1")
                toolchain = Path(env["TOOLCHAIN_FILE"]).resolve()
                sdk = toolchain.parents[2]
                build = root / "build" / "ipk"
                run(["cmake", "-S", str(root), "-B", str(build),
                     f"-DCMAKE_TOOLCHAIN_FILE={toolchain}",
                     f"-DCMAKE_C_COMPILER={sdk / 'bin/arm-webos-linux-gnueabi-gcc'}",
                     f"-DCMAKE_CXX_COMPILER={sdk / 'bin/arm-webos-linux-gnueabi-g++'}",
                     f"-DCMAKE_BUILD_TYPE={args.build_type}", "-DTARGET_WEBOS=ON", "-DBUILD_TESTS=OFF",
                     "-DBUILD_UI_SIM=OFF", "-DCMAKE_TRY_COMPILE_TARGET_TYPE=STATIC_LIBRARY",
                     "-DTHREADS_PTHREAD_ARG=2"], log, root, env)
                run(["cmake", "--build", str(build), "--parallel", str(args.jobs)], log, root, env)
                run(["cpack", "--config", str(build / "CPackConfig.cmake"), "-B", str(artifacts)], log, build, env)
        candidates = list(artifacts.glob("*.ipk"))
        if len(candidates) != 1:
            raise ValueError(f"Expected exactly one fresh IPK in {artifacts}; found {len(candidates)}")
        if state["state_sha256"] != repository(root)["state_sha256"]:
            raise ValueError("Source changed during build; previous aurora.ipk preserved. Build again from a stable checkout")
        target, metadata = publish(candidates[0], root, version)
        metadata.update({"built_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
                         "base_commit": state["head"], "source_worktree_dirty": state["dirty"],
                         "source_state_sha256": state["state_sha256"], "backend": backend,
                         "build_type": args.build_type, "output": str(target), "run_directory": str(run_dir),
                         "tv_runtime_verified": False})
        manifest = root / ".cache" / "ipk" / "latest.json"
        temporary = manifest.with_suffix(".json.tmp")
        temporary.write_text(json.dumps(metadata, indent=2) + "\n")
        os.replace(temporary, manifest)
        print(f"Verified: {target}\nVersion: {version}\nSHA-256: {metadata['sha256']}\nReceipt: {manifest}")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError, tarfile.TarError) as error:
        print(f"IPK build failed: {error}", file=sys.stderr)
        if run_dir:
            print(f"See {run_dir / 'build.log'}", file=sys.stderr)
        return 1


def make_cache(root):
    cache = root / ".cache" / "ipk"
    cache.mkdir(parents=True, exist_ok=True)
    return cache


if __name__ == "__main__":
    sys.exit(main())
